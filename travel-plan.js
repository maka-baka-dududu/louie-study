    const days = stage.days.map(([place, activity, lodging]) => `
      <li><div class="trip-day">D${++dayNumber}</div><div>
        <h3>${esc(place)}</h3><p>${esc(activity)}</p><small>住宿 · ${esc(lodging)}</small>
      </div></li>`).join('');
